/* Bake every validated set into catalog.js, the single file the game loads.
   Run after adding or editing any set:  node tools/catalog.js  */
const fs = require('fs'), path = require('path'), D = path.join(__dirname, '..');
const { PALETTE, packSet, priceFor } = require(path.join(D, 'tools/pack.js'));
const THEME_ORDER = ['City', 'Vehicles', 'Space', 'Castle', 'Pirates', 'Dino', 'Creatures', 'Hangout', 'Machines', 'Holiday'];
const files = fs.readdirSync(path.join(D, 'sets')).filter(f => f.endsWith('.json')).sort();
const out = [];
for (const f of files) {
  const set = JSON.parse(fs.readFileSync(path.join(D, 'sets', f), 'utf8'));
  if (set.id + '.json' !== f) throw new Error(`${f}: id "${set.id}" does not match the filename`);
  const { parts, steps, W, D: Dp, H } = packSet(set);
  for (const p of parts) if (!PALETTE[set.legend[p.c]]) throw new Error(`${f}: bad legend ${p.c}`);
  out.push({
    id: set.id, name: set.name, theme: set.theme, ages: set.ages, blurb: set.blurb,
    boxColor: set.boxColor, price: set.pieces ? priceFor(set.pieces) : priceFor(parts.length),
    n: parts.length, steps, W, D: Dp, H,
    legend: set.legend,
    parts: parts.map(p => [p.x, p.y, p.z, p.w, p.d, p.c, p.step]),
  });
}
out.sort((a, b) => (THEME_ORDER.indexOf(a.theme) - THEME_ORDER.indexOf(b.theme)) || a.price - b.price || a.name.localeCompare(b.name));
const body = out.map(s => `  {id:${JSON.stringify(s.id)},name:${JSON.stringify(s.name)},theme:${JSON.stringify(s.theme)},ages:${JSON.stringify(s.ages)},blurb:${JSON.stringify(s.blurb)},boxColor:${JSON.stringify(s.boxColor)},price:${s.price},n:${s.n},steps:${s.steps},W:${s.W},D:${s.D},H:${s.H},legend:${JSON.stringify(s.legend)},\n   parts:${JSON.stringify(s.parts)}}`).join(',\n');
fs.writeFileSync(path.join(D, 'catalog.js'),
  `/* GENERATED by tools/catalog.js from sets/*.json — do not hand-edit. */\nconst PALETTE = ${JSON.stringify(PALETTE, null, 1).replace(/\n\s*/g, ' ')};\n` +
  `/* parts are [x, y, z, w, d, legendChar, step] */\nconst CATALOG = [\n${body}\n];\n` +
  `if (typeof module !== 'undefined') module.exports = { CATALOG, PALETTE };\n`);
const byTheme = {};
for (const s of out) (byTheme[s.theme] = byTheme[s.theme] || []).push(s);
for (const t of THEME_ORDER) if (byTheme[t]) console.log(`${t.padEnd(10)} ${byTheme[t].length} sets  ${byTheme[t].map(s => `${s.name}($${s.price}/${s.n})`).join('  ')}`);
console.log(`\ncatalog.js: ${out.length} sets, ${out.reduce((n, s) => n + s.n, 0)} bricks total, ${(fs.statSync(path.join(D, 'catalog.js')).size / 1024).toFixed(0)}KB`);
